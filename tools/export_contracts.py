"""Exports every wire contract as a JSON Schema into interface/contracts/ (plan Q2: defined once, in Python).

The schemas come from the pydantic models: the NATS messages in nodes/incubator-1/contracts.py (`WIRE_MODELS`), the
gateway's FarmSnapshot and the website's other messages (`WEBSITE_MODELS`, interface/gateway/gateway.py). The
website's zod schemas follow them, and
tests/test_contracts_zod.py runs the same samples through both sides. The files are generated: never edit them.

Usage (from the project folder):
    python tools/export_contracts.py            write interface/contracts/<Model>.schema.json
    python tools/export_contracts.py --check    exit 1 if a file is missing or out of date (changes nothing)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "interface" / "contracts"
for _path in (ROOT / "nodes" / "incubator-1", ROOT / "interface" / "gateway"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from pydantic import BaseModel  # noqa: E402

from contracts import WIRE_MODELS  # noqa: E402
from gateway import WEBSITE_MODELS, FarmSnapshot  # noqa: E402


def models() -> list[type[BaseModel]]:
    """Every exported model, in a fixed order."""
    return [*WIRE_MODELS, FarmSnapshot, *(model for model in WEBSITE_MODELS if model not in WIRE_MODELS)]


def schema_text(model: type[BaseModel]) -> str:
    """The model's JSON Schema, as the file holds it."""
    schema = model.model_json_schema(mode="serialization")
    schema["$comment"] = "Generated by tools/export_contracts.py from the pydantic model; do not edit."
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def expected(out: Path = OUT) -> dict[Path, str]:
    """Each schema file and the text it should hold."""
    return {out / f"{model.__name__}.schema.json": schema_text(model) for model in models()}


def main(argv: list[str] | None = None, *, out: Path = OUT) -> int:
    """Command-line entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if a schema file is missing or stale")
    args = parser.parse_args(argv)
    wanted = expected(out)
    stale = [path for path, text in wanted.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    extra = sorted(path for path in out.glob("*.schema.json") if path not in wanted)
    if args.check:
        for path in stale:
            print(f"out of date: {path.name}")
        for path in extra:
            print(f"no longer a contract: {path.name}")
        return 1 if stale or extra else 0
    for path in extra:
        path.unlink()
    for path, text in wanted.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(models())} schemas to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
